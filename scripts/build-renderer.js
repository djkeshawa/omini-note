const fs = require('fs');
const path = require('path');
const esbuild = require('esbuild');

const ROOT = path.join(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'build', 'renderer');
const OUT_FILE = path.join(OUT_DIR, 'app.js');
const ENTRY = 'src/main.jsx';

function readEntrySources() {
  const entryPath = path.join(ROOT, ENTRY);
  const entry = fs.readFileSync(entryPath, 'utf8');
  const imports = [...entry.matchAll(/^\s*import\s+['"]\.\/([^'"]+)['"]\s*;?\s*$/gm)]
    .map(match => path.join('src', match[1]).replace(/\\/g, '/'));
  if (!imports.length) throw new Error(`${ENTRY} must declare renderer side-effect imports`);
  return imports;
}

const SOURCES = readEntrySources();

function transformSource(relativePath) {
  const absolutePath = path.join(ROOT, relativePath);
  const source = fs.readFileSync(absolutePath, 'utf8');
  const loader = relativePath.endsWith('.jsx') ? 'jsx' : 'js';
  const result = esbuild.transformSync(source, {
    loader,
    jsxFactory: 'React.createElement',
    jsxFragment: 'React.Fragment',
    target: 'es2022',
    legalComments: 'none',
  });
  return `\n// ${relativePath}\n(function () {\n${result.code}\n})();\n`;
}

fs.mkdirSync(OUT_DIR, { recursive: true });
const banner = `// Generated by scripts/build-renderer.js. Do not edit.\n`;
const render = `\n// renderer bootstrap\nconst root = ReactDOM.createRoot(document.getElementById('root'));\nroot.render(React.createElement(window.MnApp));\n`;
fs.writeFileSync(OUT_FILE, banner + SOURCES.map(transformSource).join('\n') + render, 'utf8');
console.log(`Built ${path.relative(ROOT, OUT_FILE)}`);
