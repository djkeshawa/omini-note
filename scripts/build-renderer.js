const fs = require('fs');
const path = require('path');
const esbuild = require('esbuild');

const ROOT = path.join(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'build', 'renderer');
const OUT_FILE = path.join(OUT_DIR, 'app.js');
const ENTRY = 'src/main.jsx';

fs.mkdirSync(OUT_DIR, { recursive: true });
esbuild.buildSync({
  entryPoints: [path.join(ROOT, ENTRY)],
  bundle: true,
  outfile: OUT_FILE,
  format: 'iife',
  platform: 'browser',
  target: 'es2022',
  jsxFactory: 'React.createElement',
  jsxFragment: 'React.Fragment',
  minify: true,
  // Component/function names survive minification: renderer wiring exposes
  // them via window globals and debugging relies on readable stacks.
  keepNames: true,
  legalComments: 'none',
  banner: { js: '// Generated by scripts/build-renderer.js. Do not edit.' },
});
console.log(`Built ${path.relative(ROOT, OUT_FILE)}`);
